#!/usr/bin/env node
// Generates rule documentation from rule metadata, so the README table, the
// skill's checklist and the linter can never drift apart.
//
//   node scripts/gen-docs.mjs          write files
//   node scripts/gen-docs.mjs --check  exit 1 if any file is out of date (CI)
//
// Requires a build (reads dist/index.js).

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATEGORIES, rules } from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const stale = [];

const code = (s) => {
  const ticks = s.includes('`') ? '``' : '`';
  const pad = s.startsWith('`') || s.endsWith('`') ? ' ' : '';
  return `${ticks}${pad}${s.replace(/\n/g, '⏎')}${pad}${ticks}`;
};
const cell = (s) => s.replace(/\|/g, '\\|');

function update(relPath, content) {
  const path = join(root, relPath);
  const current = readFileSync(path, 'utf8');
  if (current === content) return;
  if (check) stale.push(relPath);
  else {
    writeFileSync(path, content);
    console.log(`updated ${relPath}`);
  }
}

function replaceBetween(text, start, end, body) {
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a === -1 || b === -1 || b < a) throw new Error(`markers ${start} / ${end} not found`);
  return `${text.slice(0, a + start.length)}\n${body}\n${text.slice(b)}`;
}

// ---- README rules table

const table = [
  '<!-- sloplint-disable -->',
  '',
  '| Rule | Default | Catches |',
  '| --- | --- | --- |',
  ...CATEGORIES.flatMap((cat) =>
    rules
      .filter((r) => r.category === cat.id)
      .map((r) => `| ${code(r.id)} | ${r.severity} | ${cell(r.title)} |`),
  ),
  '',
  '<!-- sloplint-enable -->',
].join('\n');

const readmePath = 'README.md';
const readme = readFileSync(join(root, readmePath), 'utf8');
update(
  readmePath,
  replaceBetween(readme, '<!-- rules:start -->', '<!-- rules:end -->', table).replace(
    /<!-- rules:count -->\d+<!-- \/rules:count -->/g,
    `<!-- rules:count -->${rules.length}<!-- /rules:count -->`,
  ),
);

// ---- Skill checklist

const lines = [
  '<!-- sloplint-disable-file -- this file is a catalog of the patterns themselves -->',
  '<!-- Generated by scripts/gen-docs.mjs from src/core/rules. Do not edit by hand. -->',
  '',
  '# Pattern checklist',
  '',
  `Every rule the sloplint CLI checks (${rules.length} in total), grouped by category. Each entry says what to look for, why readers react to it, and how to fix it. Severity is the CLI default: \`error\` and \`warning\` should be fixed, \`info\` is a prompt to reread.`,
  '',
];
for (const cat of CATEGORIES) {
  lines.push(`## ${cat.title}`, '', cat.description, '');
  for (const r of rules.filter((x) => x.category === cat.id)) {
    lines.push(`### ${r.id}`, '');
    lines.push(`${r.title}. Default: \`${r.severity}\`.`, '');
    lines.push(`- Why: ${r.why}`);
    lines.push(`- Fix: ${r.suggestion}`);
    lines.push(`- Flagged: ${r.examples.bad.map(code).join(', ')}`);
    lines.push(`- Not flagged: ${r.examples.good.map(code).join(', ')}`);
    lines.push('');
  }
}
update('skills/sloplint/references/patterns.md', lines.join('\n'));

if (stale.length) {
  console.error(`Out of date: ${stale.join(', ')}. Run "npm run gen-docs".`);
  process.exit(1);
}
